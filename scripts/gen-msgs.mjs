/* Writes src/wallet/schema.gen.ts: every Msg the ledger's structs module accepts, its fields and
 * their wire kinds, read from a structsd checkout at an exact ref (the commit, not its working tree).
 *
 *   node scripts/gen-msgs.mjs /path/to/structsd v0.22.0
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const [repo, ref] = process.argv.slice(2);
if (!repo || !ref) { console.error('usage: node scripts/gen-msgs.mjs <structsd checkout> <ref>'); process.exit(1); }
const git = (...a) => execFileSync('git', ['-C', repo, ...a], { encoding: 'utf8', maxBuffer: 64 << 20 });
const DIR = 'proto/structs/structs/';
const files = git('ls-tree', '--name-only', ref, DIR).split('\n').filter((f) => f.endsWith('.proto')).sort();
const src = Object.fromEntries(files.map((f) => [f, git('show', `${ref}:${f}`).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')]));

/** The body of every `message X { … }` and `enum X { … }`, nested braces and all. */
function blocks(text, kw) {
  const out = [];
  const re = new RegExp(`\\b${kw}\\s+(\\w+)\\s*\\{`, 'g');
  let m;
  while ((m = re.exec(text))) {
    let depth = 1, i = re.lastIndex;
    for (; i < text.length && depth; i++) { if (text[i] === '{') depth++; else if (text[i] === '}') depth--; }
    out.push([m[1], text.slice(re.lastIndex, i - 1)]);
  }
  return out;
}

const enums = {};
for (const f of files) for (const [name, body] of blocks(src[f], 'enum')) {
  enums[name] = [...body.matchAll(/(\w+)\s*=\s*(-?\d+)/g)].map((x) => [x[1], Number(x[2])]);
}
const messages = {};
for (const f of files) for (const [name, body] of blocks(src[f], 'message')) if (!(name in messages)) messages[name] = body;

const SCALARS = new Set(['string', 'uint64', 'int64', 'uint32', 'int32', 'bool', 'bytes']);
function fields(body, owner) {
  const out = [];
  for (const m of body.replace(/\boption\s*\([^)]*\)\s*=[^;]*;/g, '').matchAll(/(repeated\s+)?([\w.]+)\s+(\w+)\s*=\s*(\d+)\s*(\[[^\]]*\])?\s*;/g)) {
    const [, rep, type, name, no, opts = ''] = m;
    const f = { name, no: Number(no), repeated: !!rep };
    if (type === 'string' && /LegacyDec/.test(opts)) f.kind = 'dec';
    else if (SCALARS.has(type)) f.kind = type;
    else if (type === 'cosmos.base.v1beta1.Coin') f.kind = 'coin';
    else if (enums[type]) { f.kind = 'enum'; f.enum = type; }
    else if (messages[type]) { f.kind = 'msg'; f.msg = type; }
    else throw new Error(`${owner}.${name}: unknown type ${type}`);
    out.push(f);
  }
  return out;
}

const service = blocks(src[`${DIR}tx.proto`], 'service')[0][1];
const MSGS = {};
const NESTED = {};
const nest = (list) => { for (const f of list) if (f.kind === 'msg' && !NESTED[f.msg]) { NESTED[f.msg] = []; NESTED[f.msg] = fields(messages[f.msg], f.msg); nest(NESTED[f.msg]); } };
for (const [, rpc, msg] of service.matchAll(/rpc\s+(\w+)\s*\(\s*(\w+)\s*\)/g)) {
  if (MSGS[msg]) continue;
  MSGS[msg] = { rpc, fields: fields(messages[msg], msg) };
  nest(MSGS[msg].fields);
}
// Enums a Msg field names (in the order they first appear), then the ones the client reads by name.
const READ = ['raidStatus', 'fleetStatus', 'planetStatus', 'guildJoinType', 'registrationStatus', 'techActiveWeaponry', 'techPassiveWeaponry', 'techUnitDefenses'];
const named = [];
for (const f of Object.values(MSGS).flatMap((m) => m.fields).concat(Object.values(NESTED).flat())) if (f.enum && !named.includes(f.enum)) named.push(f.enum);
const ENUMS = Object.fromEntries([...named, ...READ.filter((n) => !named.includes(n))].map((n) => [n, enums[n]]));

const out = `/* GENERATED by scripts/gen-msgs.mjs from ledger ${ref} proto/structs/structs/tx.proto — do not edit.
 * Every Msg the chain's ledger module accepts, its fields and their wire kinds. */
/* eslint-disable */

export type FieldKind = 'string' | 'uint64' | 'int64' | 'uint32' | 'int32' | 'bool' | 'bytes' | 'enum' | 'coin' | 'dec' | 'msg';
export interface FieldSpec { name: string; no: number; repeated: boolean; kind: FieldKind; enum?: string; msg?: string; doc?: string }
export interface MsgSpec { rpc: string; doc?: string; fields: FieldSpec[] }

export const PROTO_REF = ${JSON.stringify(ref)};
export const MSGS: Record<string, MsgSpec> = ${JSON.stringify(MSGS, null, 1)};
export const NESTED: Record<string, FieldSpec[]> = ${JSON.stringify(NESTED, null, 1)};
export const ENUMS: Record<string, [string, number][]> = ${JSON.stringify(ENUMS)};
`;
writeFileSync(fileURLToPath(new URL('../src/wallet/schema.gen.ts', import.meta.url)), out);
console.log(`schema.gen.ts: ${Object.keys(MSGS).length} messages from ${ref}`);
